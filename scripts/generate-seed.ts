// Generates supabase/seed.sql from src/lib/data/fixtures.ts so demo and DB seed never drift.
// Run: npm run seed:generate
import { writeFileSync } from "node:fs";
import {
  DEMO_APPOINTMENTS,
  TCUTZ_ID,
  buildCustomers,
  buildHaircutHistory,
  buildHaircutProfiles,
  fid,
  tcutzSalon,
  tcutzServices,
  tcutzStaff,
} from "../src/lib/data/fixtures.ts";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const today = new Date().toISOString().slice(0, 10);
const out: string[] = [
  "-- GENERATED by scripts/generate-seed.ts — do not edit by hand.",
  "-- Tcutz pilot config + SYNTHETIC customers (555-01xx numbers). is_demo = true.",
  "begin;",
];
const s = tcutzSalon;
out.push(
  `insert into salons (id, slug, name, timezone, phone_e164, address, website_url, brand, is_demo, status, provider_number_e164) values (${q(s.id)}, ${q(s.slug)}, ${q(s.name)}, ${q(s.timezone)}, ${q(s.phone)}, ${q(s.address)}, ${q(s.websiteUrl)}, ${q(JSON.stringify(s.brand))}::jsonb, true, 'trial', ${q(s.providerNumber)});`,
  `insert into salon_settings (salon_id, slot_interval_minutes, min_booking_notice_minutes, max_advance_days, hold_minutes, business_hours, quiet_hours, missed_call_settings) values (${q(s.id)}, ${s.settings.slotIntervalMinutes}, ${s.settings.minBookingNoticeMinutes}, ${s.settings.maxAdvanceDays}, ${s.settings.holdMinutes}, ${q(JSON.stringify(s.settings.businessHours))}::jsonb, ${q(JSON.stringify(s.settings.quietHours))}::jsonb, ${q(JSON.stringify({ enabled: s.settings.missedCallTextBack.enabled, dedupe_hours: s.settings.missedCallTextBack.dedupeHours, upcoming_window_days: s.settings.missedCallTextBack.upcomingWindowDays }))}::jsonb);`,
  `insert into subscription_plans (code, name, monthly_price_cents, included_ai_minutes, included_sms) values ('pilot', 'Pilot', 14900, 600, 1000) on conflict (code) do nothing;`,
);
for (const sv of tcutzServices) {
  out.push(
    `insert into services (id, salon_id, name_en, name_vi, price_cents, price_type, duration_minutes, cleanup_minutes, requires_approval, sort_order) values (${q(sv.id)}, ${q(TCUTZ_ID)}, ${q(sv.nameEn)}, ${q(sv.nameVi)}, ${sv.priceCents}, ${q(sv.priceType)}, ${sv.durationMinutes}, ${sv.cleanupMinutes}, ${sv.requiresApproval}, ${sv.sortOrder});`,
  );
}
for (const st of tcutzStaff) {
  out.push(
    `insert into staff (id, salon_id, display_name, color, sort_order) values (${q(st.id)}, ${q(TCUTZ_ID)}, ${q(st.displayName)}, ${q(st.color)}, ${st.sortOrder});`,
  );
  for (const [wd, ranges] of Object.entries(st.workingHours)) {
    for (const r of ranges ?? []) {
      out.push(
        `insert into staff_working_hours (salon_id, staff_id, weekday, start_time, end_time) values (${q(TCUTZ_ID)}, ${q(st.id)}, ${wd}, ${q(r.open)}, ${q(r.close)});`,
      );
    }
  }
  for (const link of st.services) {
    out.push(
      `insert into staff_services (salon_id, staff_id, service_id, duration_minutes_override) values (${q(TCUTZ_ID)}, ${q(st.id)}, ${q(link.serviceId)}, ${q(link.durationOverrideMinutes)});`,
    );
  }
}
for (const c of buildCustomers(today)) {
  out.push(
    `insert into customers (id, salon_id, first_name, last_name, phone_e164, preferred_language, preferred_staff_id, first_visit_at, last_visit_at, completed_visits, lifetime_spend_cents, notes, is_synthetic) values (${q(c.id)}, ${q(TCUTZ_ID)}, ${q(c.firstName)}, ${q(c.lastName)}, ${q(c.phoneE164)}, ${q(c.preferredLanguage)}, ${q(c.preferredStaffId)}, ${q(c.firstVisitAt)}, ${q(c.lastVisitAt)}, ${c.completedVisits}, ${c.lifetimeSpendCents}, ${q(c.notes)}, true);`,
    `insert into customer_preferences (customer_id, salon_id, usual_service_id) values (${q(c.id)}, ${q(TCUTZ_ID)}, ${q(c.usualServiceId)});`,
    `insert into customer_consents (salon_id, customer_id, consent, granted, method) values (${q(TCUTZ_ID)}, ${q(c.id)}, 'sms_transactional', true, 'synthetic_seed');`,
  );
  if (c.photoConsent)
    out.push(
      `insert into customer_consents (salon_id, customer_id, consent, granted, method) values (${q(TCUTZ_ID)}, ${q(c.id)}, 'photo', true, 'synthetic_seed');`,
    );
}
for (const p of buildHaircutProfiles(today)) {
  out.push(
    `insert into haircut_profiles (customer_id, salon_id, style, clipper_guard, fade_type, side_length, top_length, back_length, scissor_notes, hairline, beard, color_formula, products, stylist_notes) values (${q(p.customerId)}, ${q(TCUTZ_ID)}, ${q(p.style)}, ${q(p.clipperGuard)}, ${q(p.fadeType)}, ${q(p.sideLength)}, ${q(p.topLength)}, ${q(p.backLength)}, ${q(p.scissorNotes)}, ${q(p.hairline)}, ${q(p.beard)}, ${q(p.colorFormula)}, ${q(p.products)}, ${q(p.stylistNotes)});`,
  );
}
for (const h of buildHaircutHistory(today)) {
  out.push(
    `insert into haircut_history (id, salon_id, customer_id, staff_id, cut_on, snapshot, customer_feedback) values (${q(h.id)}, ${q(TCUTZ_ID)}, ${q(h.customerId)}, ${q(h.staffId)}, (current_date - ${Math.round((Date.parse(today) - Date.parse(h.cutOn)) / 86_400_000)}), ${q(JSON.stringify(h.snapshot))}::jsonb, ${q(h.customerFeedback)});`,
  );
}
// Appointments relative to the salon's local "today" at seed time, via book_appointment (exercises the real path).
for (const a of DEMO_APPOINTMENTS) {
  const local = `((date_trunc('day', now() at time zone ${q(s.timezone)}) + interval '${a.dayOffset} days' + time ${q(a.time)}) at time zone ${q(s.timezone)})`;
  out.push(
    `select public.book_appointment(${q(TCUTZ_ID)}, ${q(a.staffId)}, ${q(a.customerN ? fid(4, a.customerN) : null)}, ${local}, array[${a.serviceIds.map(q).join(",")}]::uuid[], ${q(a.source)}::appointment_source, ${q(`seed-${a.n}-demo`)}, ${q(a.note)}, null, null, ${q(a.status)}::appointment_status);`,
  );
}
out.push("commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`Wrote supabase/seed.sql (${out.length} lines)`);
