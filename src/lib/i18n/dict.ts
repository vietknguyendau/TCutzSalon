export function formatDateLong(date: string, lang: "en" | "vi"): string {
  const d = new Date(`${date}T12:00:00Z`);
  return new Intl.DateTimeFormat(lang === "vi" ? "vi-VN" : "en-US", {
    weekday: "long",
    month: "long",
    day: "numeric",
    timeZone: "UTC",
  }).format(d);
}

export function formatDateParts(date: string, lang: "en" | "vi") {
  const d = new Date(`${date}T12:00:00Z`);
  const loc = lang === "vi" ? "vi-VN" : "en-US";
  return {
    weekday: new Intl.DateTimeFormat(loc, { weekday: "short", timeZone: "UTC" }).format(d),
    day: d.getUTCDate(),
    month: new Intl.DateTimeFormat(loc, { month: "short", timeZone: "UTC" }).format(d),
  };
}
